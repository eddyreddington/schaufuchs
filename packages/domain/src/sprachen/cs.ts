/** Množné číslo: 1 zvíře, 2–4 zvířata, 5+ zvířat. */
function mnozne(n: number, jedno: string, nekolik: string, mnoho: string): string {
  if (n === 1) return jedno;
  return n >= 2 && n <= 4 ? nekolik : mnoho;
}

