/** České množné číslo: 1 → jeden, 2–4 → několik, jinak → mnoho. */
export function mnozne(n: number, jeden: string, nekolik: string, mnoho: string): string {
  if (n === 1) return jeden;
  return n >= 2 && n <= 4 ? nekolik : mnoho;
}

