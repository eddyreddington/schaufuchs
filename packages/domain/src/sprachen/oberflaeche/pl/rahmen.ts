/** Polnische Mehrzahl: 1 znak, 2–4 znaki (nicht 12–14), sonst znaków. */
const znaki = (n: number) => {
  const r10 = n % 10, r100 = n % 100;
  if (n === 1) return "znak";
  return r10 >= 2 && r10 <= 4 && (r100 < 12 || r100 > 14) ? "znaki" : "znaków";
};

