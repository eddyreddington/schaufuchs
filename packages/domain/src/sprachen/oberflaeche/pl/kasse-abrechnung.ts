/** Liczba z rzeczownikiem w odpowiedniej formie (1 / 2–4 / 5+). */
export function liczba(n: number, jeden: string, kilka: string, wiele: string): string {
  const d = n % 10;
  const s = n % 100;
  return `${n} ${n === 1 ? jeden : d >= 2 && d <= 4 && (s < 12 || s > 14) ? kilka : wiele}`;
}

