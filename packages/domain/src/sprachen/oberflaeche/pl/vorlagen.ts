/** Liczba mnoga: 1 – jeden, 2–4 (bez 12–14) – kilka, pozostałe – wiele. */
const mz = (n: number, jeden: string, kilka: string, wiele: string) => {
  const j = n % 10;
  const d = n % 100;
  return n === 1 ? jeden : j >= 2 && j <= 4 && (d < 12 || d > 14) ? kilka : wiele;
};

