/** Liczba w tekście serwera (napis): 1 / 2–4 / 5+. */
const mn = (n: string, jeden: string, kilka: string, wiele: string) => {
  const z = Number(n);
  return z === 1 ? jeden : [2, 3, 4].includes(z % 10) && ![12, 13, 14].includes(z % 100) ? kilka : wiele;
};

