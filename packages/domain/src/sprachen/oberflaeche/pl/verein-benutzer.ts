/** Polska liczba mnoga: 1 → jeden, 2–4 (bez 12–14) → kilka, reszta → wiele. */
export function mnoga(n: number, jeden: string, kilka: string, wiele: string): string {
  if (n === 1) return jeden;
  const r10 = n % 10;
  const r100 = n % 100;
  return r10 >= 2 && r10 <= 4 && (r100 < 12 || r100 > 14) ? kilka : wiele;
}

