/** Liczba mnoga: 1 zwierzę, 2–4 zwierzęta, 5+ zwierząt (12–14 też „zwierząt“). */
function mnoga(n: number, jeden: string, kilka: string, wiele: string): string {
  const d = n % 10;
  const s = n % 100;
  if (n === 1) return jeden;
  return d >= 2 && d <= 4 && (s < 12 || s > 14) ? kilka : wiele;
}

